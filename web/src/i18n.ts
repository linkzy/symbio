const DICTS: Record<Locale, Dict> = { en, "pt-BR": ptBR };

export function currentLocale(): Locale {
  try {
    const saved = localStorage.getItem(KEY);
    return saved === "pt-BR" || saved === "en" ? saved : "en";
  } catch {
    return "en";
  }
}

export function applyLocale(locale = currentLocale()) {
  if (typeof document !== "undefined") document.documentElement.lang = locale === "pt-BR" ? "pt-BR" : "en";
}

export function setLocale(locale: Locale) {
  try {
    localStorage.setItem(KEY, locale);
  } catch {}
  applyLocale(locale);
  if (typeof dispatchEvent !== "undefined") dispatchEvent(new Event(EVENT));
}

export function t(key: string, params?: Record<string, string | number>): string {
  const locale = currentLocale();
  let text = DICTS[locale][key] ?? DICTS.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

export function useI18n() {
  const [locale, set] = useState<Locale>(currentLocale);
  useEffect(() => {
    const update = () => set(currentLocale());
    addEventListener(EVENT, update);
    const onStorage = (e: StorageEvent) => {
      if (e.key === KEY) {
        applyLocale();
        update();
      }
    };
    addEventListener("storage", onStorage);
    return () => {
      removeEventListener(EVENT, update);
      removeEventListener("storage", onStorage);
    };
  }, []);
  const translate = (key: string, params?: Record<string, string | number>) => {
    let text = DICTS[locale][key] ?? DICTS.en[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
  };
  return { locale, setLocale, t: translate };
}
